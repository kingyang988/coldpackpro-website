window.currentLang = 'en';

function setLanguage(lang) {
  window.currentLang = 'en';
  document.documentElement.lang = 'en';
  try {
    localStorage.setItem('coldpackpro_lang', 'en');
  } catch(e) {}

  const translations = i18nTranslations.en;
  if (!translations) return;

  // Update elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[key]) {
      el.textContent = translations[key];
    }
  });

  // Update placeholders with data-i18n-ph
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (translations[key]) {
      el.placeholder = translations[key];
    }
  });

  // Update page title and description
  if (translations['page.title']) {
    document.title = translations['page.title'];
  }
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && translations['page.desc']) {
    metaDesc.setAttribute('content', translations['page.desc']);
  }

  // Synchronize all catalog links so they pass ?lang=en
  document.querySelectorAll('a[href*="/catalog"]').forEach(a => {
    try {
      const u = new URL(a.getAttribute('href'), window.location.origin);
      u.searchParams.set('lang', 'en');
      a.setAttribute('href', u.pathname + u.search + u.hash);
    } catch(e) {
      a.setAttribute('href', '/catalog?lang=en');
    }
  });

  if (typeof window.updateInquiryUploadUI === 'function') {
    window.updateInquiryUploadUI();
  }
}

// Global click handler to guarantee correct language param on any catalog navigation
document.addEventListener('click', function(e) {
  const link = e.target.closest('a[href*="/catalog"]');
  if (link) {
    try {
      const u = new URL(link.getAttribute('href'), window.location.origin);
      u.searchParams.set('lang', 'en');
      link.setAttribute('href', u.pathname + u.search + u.hash);
    } catch(err) {
      link.setAttribute('href', '/catalog?lang=en');
    }
  }
});

// Auto-initialize on load: Default strictly to 'en'
document.addEventListener('DOMContentLoaded', () => {
  try {
    localStorage.setItem('coldpackpro_lang', 'en');
  } catch(e) {}
  setLanguage('en');
});

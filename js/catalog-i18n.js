/**
 * Apply the English language to the entire catalog page
 */
function applyCatalogLanguage(lang) {
  const data = CATALOG_I18N.en;
  if (!data) return;

  // 1. Update html lang attribute
  document.documentElement.lang = 'en';

  // 2. Update document title & meta tags
  if (data.page_title) {
    document.title = data.page_title;
  }
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && data.page_desc) {
    metaDesc.setAttribute('content', data.page_desc);
  }

  // 3. Update all static elements with [data-cat-i18n]
  document.querySelectorAll('[data-cat-i18n]').forEach(el => {
    const key = el.getAttribute('data-cat-i18n');
    if (data[key]) {
      el.textContent = data[key];
    }
  });

  // 4. Update all static elements with [data-cat-i18n-html]
  document.querySelectorAll('[data-cat-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-cat-i18n-html');
    if (data[key]) {
      el.innerHTML = data[key];
    }
  });

  // 5. Update inputs placeholders with [data-cat-i18n-ph]
  document.querySelectorAll('[data-cat-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-cat-i18n-ph');
    if (data[key]) {
      el.placeholder = data[key];
    }
  });

  // 6. Update titles/tooltips with [data-cat-i18n-title]
  document.querySelectorAll('[data-cat-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-cat-i18n-title');
    if (data[key]) {
      el.title = data[key];
    }
  });

  // 7. Update links to use lang=en
  document.querySelectorAll('a[href="/"], a[href^="/?"], a[href^="https://coldpackpro.com"]').forEach(a => {
    const rawHref = a.getAttribute('href');
    if (rawHref === '/' || rawHref === 'https://coldpackpro.com' || rawHref === 'https://coldpackpro.com/') {
      a.setAttribute('href', '/?lang=en');
    } else {
      try {
        const u = new URL(rawHref, window.location.origin);
        u.searchParams.set('lang', 'en');
        a.setAttribute('href', u.pathname + u.search + u.hash);
      } catch(e) {
        a.setAttribute('href', '/?lang=en');
      }
    }
  });

  // 8. Update Quick Search elements
  const searchInput = document.getElementById('quickSearchInput');
  if (searchInput && data.search_ph) {
    searchInput.placeholder = data.search_ph;
    searchInput.title = 'Search model or capacity to locate product';
  }
  const clearBtn = document.getElementById('quickSearchClearBtn');
  if (clearBtn && data.search_clear_title) {
    clearBtn.title = data.search_clear_title;
  }

  // 9. Persist to localStorage
  try {
    localStorage.setItem('coldpackpro_lang', 'en');
  } catch(e) {}
}

window.CATALOG_I18N = CATALOG_I18N;
window.getCatalogLang = getCatalogLang;
window.setCatalogLanguage = setCatalogLanguage;
window.applyCatalogLanguage = applyCatalogLanguage;
